-- CASE_FILE 사건 제목과 브리핑
CREATE TABLE "CASE_FILE" (
    "CASE_ID" NUMBER(10,0) CONSTRAINT "NN_CASE_FILE_CASE_ID" NOT NULL,
    "TITLE" VARCHAR2(100 CHAR) CONSTRAINT "NN_CASE_FILE_TITLE" NOT NULL,
    "BRIEFING" VARCHAR2(1000 CHAR) CONSTRAINT "NN_CASE_FILE_BRIEFING" NOT NULL,
     CONSTRAINT "CK_CASE_ID" CHECK (case_id >= 1),
     CONSTRAINT "PK_CASE_FILE" PRIMARY KEY ("CASE_ID")
);

-- AREA 시설 구역과 시작·탈출 지점
CREATE TABLE "AREA" (
    "CASE_ID" NUMBER(10,0) CONSTRAINT "NN_AREA_CASE_ID" NOT NULL,
    "AREA_NO" NUMBER(10,0) CONSTRAINT "NN_AREA_AREA_NO" NOT NULL,
    "AREA_NAME" VARCHAR2(100 CHAR) CONSTRAINT "NN_AREA_AREA_NAME" NOT NULL,
    "AREA_TYPE" VARCHAR2(6 CHAR) CONSTRAINT "NN_AREA_AREA_TYPE" NOT NULL,
    "MAP_X" NUMBER(4,0) CONSTRAINT "NN_AREA_MAP_X" NOT NULL,
    "MAP_Y" NUMBER(4,0) CONSTRAINT "NN_AREA_MAP_Y" NOT NULL,
     CONSTRAINT "CK_AREA_NO" CHECK (area_no >= 1),
     CONSTRAINT "CK_AREA_AREA_TYPE" CHECK (area_type IN ('START','NORMAL','EXIT')),
     CONSTRAINT "CK_AREA_MAP_X" CHECK (map_x BETWEEN 0 AND 9999),
     CONSTRAINT "CK_AREA_MAP_Y" CHECK (map_y BETWEEN 0 AND 9999),
     CONSTRAINT "PK_AREA" PRIMARY KEY ("CASE_ID", "AREA_NO"),
     CONSTRAINT "FK_AREA_CASE" FOREIGN KEY ("CASE_ID")
      REFERENCES "CASE_FILE" ("CASE_ID")
);

-- INSPECTION 구역별 단서, 대화, 조사 기록
CREATE TABLE "INSPECTION" (
    "CASE_ID" NUMBER(10,0) CONSTRAINT "NN_INSPECTION_CASE_ID" NOT NULL,
    "INSPECTION_NO" NUMBER(10,0) CONSTRAINT "NN_INSPECTION_INSPECTION_NO" NOT NULL,
    "AREA_NO" NUMBER(10,0) CONSTRAINT "NN_INSPECTION_AREA_NO" NOT NULL,
    "INSPECTION_TYPE" VARCHAR2(8 CHAR) CONSTRAINT "NN_INSPECTION_INSPECTION_TYPE" NOT NULL,
    "TITLE" VARCHAR2(100 CHAR) CONSTRAINT "NN_INSPECTION_TITLE" NOT NULL,
    "CONTENT" VARCHAR2(1000 CHAR) CONSTRAINT "NN_INSPECTION_CONTENT" NOT NULL,
    "DISPLAY_ORDER" NUMBER(3,0) CONSTRAINT "NN_INSPECTION_DISPLAY_ORDER" NOT NULL,
     CONSTRAINT "CK_INSPECTION_NO" CHECK (inspection_no >= 1),
     CONSTRAINT "CK_INSPECTION_INSPECTION_TYPE" CHECK (inspection_type IN ('CLUE','STORY','DIALOGUE')),
     CONSTRAINT "CK_INSPECTION_DISPLAY_ORDER" CHECK (display_order BETWEEN 1 AND 999),
     CONSTRAINT "PK_INSPECTION" PRIMARY KEY ("CASE_ID", "INSPECTION_NO"),
     CONSTRAINT "UQ_INSPECTION_ORDER" UNIQUE ("CASE_ID", "AREA_NO", "DISPLAY_ORDER"),
     CONSTRAINT "FK_INSPECTION_AREA" FOREIGN KEY ("CASE_ID", "AREA_NO")
      REFERENCES "AREA" ("CASE_ID", "AREA_NO")
);

-- PUZZLE 퍼즐의 정답, 실마리, 선행 조건
CREATE TABLE "PUZZLE" (
    "CASE_ID" NUMBER(10,0) CONSTRAINT "NN_PUZZLE_CASE_ID" NOT NULL,
    "PUZZLE_NO" NUMBER(10,0) CONSTRAINT "NN_PUZZLE_PUZZLE_NO" NOT NULL,
    "AREA_NO" NUMBER(10,0) CONSTRAINT "NN_PUZZLE_AREA_NO" NOT NULL,
    "PUZZLE_NAME" VARCHAR2(100 CHAR) CONSTRAINT "NN_PUZZLE_PUZZLE_NAME" NOT NULL,
    "PUZZLE_TYPE" VARCHAR2(6 CHAR) CONSTRAINT "NN_PUZZLE_PUZZLE_TYPE" NOT NULL,
    "PROMPT" VARCHAR2(500 CHAR) CONSTRAINT "NN_PUZZLE_PROMPT" NOT NULL,
    "ANSWER_KEY" VARCHAR2(50 CHAR) CONSTRAINT "NN_PUZZLE_ANSWER_KEY" NOT NULL,
    "HINT_TEXT" VARCHAR2(500 CHAR) CONSTRAINT "NN_PUZZLE_HINT_TEXT" NOT NULL,
    "SOLVED_TEXT" VARCHAR2(500 CHAR) CONSTRAINT "NN_PUZZLE_SOLVED_TEXT" NOT NULL,
    "PREREQUISITE_PUZZLE_NO" NUMBER(10,0),
    "REQUIRED_FREE_HANDS" NUMBER(1,0) CONSTRAINT "NN_PUZZLE_REQUIRED_FREE_HANDS" NOT NULL,
     CONSTRAINT "CK_PUZZLE_NO" CHECK (puzzle_no >= 1),
     CONSTRAINT "CK_PUZZLE_SELF" CHECK (prerequisite_puzzle_no IS NULL OR prerequisite_puzzle_no <> puzzle_no),
     CONSTRAINT "CK_PUZZLE_PUZZLE_TYPE" CHECK (puzzle_type IN ('CODE','POWER','VERIFY')),
     CONSTRAINT "CK_PUZZLE_REQUIRED_FREE_HANDS" CHECK (required_free_hands IN (0,1,2)),
     CONSTRAINT "PK_PUZZLE" PRIMARY KEY ("CASE_ID", "PUZZLE_NO"),
     CONSTRAINT "FK_PUZZLE_AREA" FOREIGN KEY ("CASE_ID", "AREA_NO")
      REFERENCES "AREA" ("CASE_ID", "AREA_NO"),
     CONSTRAINT "FK_PUZZLE_PREREQUISITE" FOREIGN KEY ("CASE_ID", "PREREQUISITE_PUZZLE_NO")
      REFERENCES "PUZZLE" ("CASE_ID", "PUZZLE_NO")
);

